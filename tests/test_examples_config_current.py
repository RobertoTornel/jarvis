"""examples/config.json must stay in sync with the current config.py defaults.

``examples/config.json`` is generated by ``scripts/generate_config_examples.py``
from ``get_default_config()`` (via ``export_example_config()``), but nothing
pinned it down, so it went stale: it still advertised ``tts_engine: "piper"``
after the default became ``"fish"``, its wake aliases and fuzzy ratio were the
old Jervis-era values, the whole speech-to-text and Fish Audio surface was
missing, and it still listed the removed macOS ``allowlist_bundles``.

These tests compare the shipped example against the real defaults, so a config
surface change that is not regenerated fails here instead of shipping a
misleading example.  The reference of record is
``claire.config.get_default_config()``; a single key, ``db_path``, is compared
explicitly instead of generically because the generator deliberately rewrites it
to a user-friendly ``~/...`` path (see ``NON_GENERIC_KEYS``).
"""

import json
from pathlib import Path

import pytest

from claire.config import export_example_config, get_default_config

ROOT = Path(__file__).resolve().parents[1]
EXAMPLE_PATH = ROOT / "examples" / "config.json"

#: Keys named in the task that must be present with these exact semantics.
STT_KEYS = (
    "stt_engine",
    "stt_model_path",
    "stt_model_kind",
    "stt_device",
    "streaming_stt_engine",
    "streaming_stt_model_dir",
    "streaming_stt_num_threads",
)
FISH_KEYS = ("fish_voice_id", "fish_key_file", "fish_latency", "fish_model")

#: The Claire wake surface, pinned on purpose: the old Jervis-era aliases must
#: never come back, and adding an alias is a deliberate change that belongs here.
CLAIRE_ALIASES = ["clair", "clare", "claira", "claya", "klair", "klare", "claires"]
WAKE_FUZZY_RATIO = 0.82

#: ``export_example_config()`` rewrites exactly this key to a portable path, so
#: it cannot be compared generically against the machine-specific default.
#: It is asserted explicitly in ``test_db_path_uses_the_generator_user_path``.
#: Adding an entry here is a decision, not a shortcut - every key listed must
#: have its own explicit assertion.
NON_GENERIC_KEYS = frozenset({"db_path"})
EXAMPLE_DB_PATH = "~/.local/share/claire/claire.db"

#: Removed surfaces.  Their *names* must never reappear in the example config.
FORBIDDEN_KEY_PATTERNS = ("dictation", "macos", "darwin", "windows", "win32")


@pytest.fixture(scope="module")
def example() -> dict:
    """The shipped example, parsed as JSON."""
    return json.loads(EXAMPLE_PATH.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def defaults() -> dict:
    """The current defaults the example must mirror."""
    return get_default_config()


@pytest.mark.unit
def test_example_config_is_valid_json(example):
    """The shipped example must parse as JSON, not merely look like JSON."""
    assert isinstance(example, dict)
    assert example, "examples/config.json must not be empty"


@pytest.mark.unit
def test_example_config_has_exactly_the_default_keys(example, defaults):
    """No key may be missing from, or invented by, the example config."""
    missing = sorted(set(defaults) - set(example))
    extra = sorted(set(example) - set(defaults))
    assert not missing, f"examples/config.json is missing defaults: {missing}"
    assert not extra, f"examples/config.json has keys config.py does not: {extra}"


@pytest.mark.unit
def test_every_example_value_matches_the_current_default(example, defaults):
    """Every comparable value must equal its default, so the example cannot drift."""
    mismatches = {}
    not_compared_generically = {}

    for key, value in example.items():
        if key in NON_GENERIC_KEYS:
            # Reported rather than skipped silently; asserted by name elsewhere.
            not_compared_generically[key] = value
            continue
        if key not in defaults:
            # Already a failure in the key-set test; never silently ignored here.
            not_compared_generically[key] = value
            continue
        if value != defaults[key]:
            mismatches[key] = {"example": value, "default": defaults[key]}

    assert not mismatches, (
        "examples/config.json is stale (key: example vs default): "
        f"{mismatches} - run scripts/generate_config_examples.py"
    )
    assert set(not_compared_generically) == set(NON_GENERIC_KEYS), (
        "keys were not compared generically: "
        f"{sorted(not_compared_generically)} - if a key is intentionally "
        "excluded from the generic comparison, add an explicit assertion for "
        "it and document it in NON_GENERIC_KEYS"
    )


@pytest.mark.unit
def test_db_path_uses_the_generator_user_path(example, defaults):
    """db_path is the one key the generator rewrites; assert both sides."""
    assert example["db_path"] == EXAMPLE_DB_PATH, (
        "examples/config.json must carry the portable example db_path "
        f"{EXAMPLE_DB_PATH!r}, not {example['db_path']!r}"
    )
    # The default is machine-specific, which is exactly why it is not compared
    # generically: the example must never ship a real absolute home path.
    assert defaults["db_path"] != EXAMPLE_DB_PATH


@pytest.mark.unit
def test_example_config_is_what_the_generator_writes(example):
    """The file must equal the generator output exactly (modulo JSON encoding)."""
    generated = json.loads(json.dumps(export_example_config(include_db_path=False)))
    assert example == generated, (
        "examples/config.json is not what scripts/generate_config_examples.py "
        "writes - rerun it"
    )


@pytest.mark.unit
def test_tts_engine_is_fish(example, defaults):
    """The removed piper default must not linger in the example."""
    assert example["tts_engine"] == "fish", (
        f"examples/config.json tts_engine is {example['tts_engine']!r}, "
        "default is 'fish' - the old 'piper' value must not come back"
    )
    assert example["tts_engine"] == defaults["tts_engine"]


@pytest.mark.unit
def test_speech_to_text_keys_match_defaults(example, defaults):
    """The speech-to-text surface must be present and current."""
    for key in STT_KEYS:
        assert key in example, f"examples/config.json is missing STT key {key!r}"
        assert example[key] == defaults[key], (
            f"{key!r} in examples/config.json is {example[key]!r}, "
            f"default is {defaults[key]!r}"
        )
    assert example["stt_engine"] == "parakeet"
    assert example["streaming_stt_engine"] == "sherpa"
    assert example["streaming_stt_num_threads"] == 2


@pytest.mark.unit
def test_fish_audio_keys_match_defaults(example, defaults):
    """The Fish Audio surface must be present and current."""
    for key in FISH_KEYS:
        assert key in example, f"examples/config.json is missing Fish key {key!r}"
        assert example[key] == defaults[key], (
            f"{key!r} in examples/config.json is {example[key]!r}, "
            f"default is {defaults[key]!r}"
        )
    assert example["fish_latency"] == "low", (
        "'normal' latency is slow and must not be the conversation default"
    )


@pytest.mark.unit
def test_wake_word_and_claire_aliases_are_current(example, defaults):
    """The wake word, full Claire alias list and fuzzy ratio must be current."""
    assert example["wake_word"] == "claire"
    assert example["wake_word"] == defaults["wake_word"]

    aliases = example["wake_aliases"]
    assert isinstance(aliases, list)
    assert aliases == CLAIRE_ALIASES, (
        f"wake_aliases in examples/config.json are {aliases!r}, expected the "
        f"Claire alias list {CLAIRE_ALIASES!r}"
    )
    assert aliases == defaults["wake_aliases"]

    assert example["wake_fuzzy_ratio"] == WAKE_FUZZY_RATIO
    assert example["wake_fuzzy_ratio"] == defaults["wake_fuzzy_ratio"]


@pytest.mark.unit
def test_allowlist_bundles_is_empty(example, defaults):
    """The macOS bundle ids were removed; the example must ship an empty list."""
    assert example["allowlist_bundles"] == [], (
        "examples/config.json still lists allowlist bundles; Claire is "
        f"Linux-only, got {example['allowlist_bundles']!r}"
    )
    assert example["allowlist_bundles"] == defaults["allowlist_bundles"]


@pytest.mark.unit
def test_no_key_name_contains_dictation(example):
    """Dictation was removed; no key may mention it."""
    offenders = [key for key in example if "dictation" in key.lower()]
    assert not offenders, f"dictation keys reappeared: {offenders}"


@pytest.mark.unit
def test_no_macos_or_windows_keys(example):
    """macOS/Windows-only keys were removed and must not return."""
    offenders = [
        key
        for key in example
        if any(pattern in key.lower() for pattern in FORBIDDEN_KEY_PATTERNS)
    ]
    assert not offenders, f"removed platform keys reappeared: {offenders}"
