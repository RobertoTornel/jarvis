#!/bin/bash
# Build the frozen app for manual testing on Linux. This produces
# dist/Claire/. There is no Inno-equivalent installer step, so the bundle
# directory itself is the artefact you'd ship.

set -euo pipefail

cd "$(dirname "$0")/.."
PROJECT_ROOT="$(pwd)"

# Stamp a dev version file so claire.get_version() works in the bundle.
#
# The version must be PEP 440-valid, not just human-readable: this file is also
# the `dynamic = ["version"]` source for the pyproject build, and `pip install`
# rejects values such as "dev-abc1234" with InvalidVersion. A local version
# segment (+g<sha>) keeps the commit readable while staying valid.
GIT_SHA="$(git rev-parse --short=7 HEAD 2>/dev/null || echo local)"
DEV_VERSION="0.1.0.dev0+g${GIT_SHA}"
echo "[build_installer] Stamping dev _version.py (${DEV_VERSION})..."
cat > "${PROJECT_ROOT}/src/claire/_version.py" <<EOF
# Auto-generated by scripts/build_installer.sh
VERSION = "${DEV_VERSION}"
RELEASE_CHANNEL = "develop"
EOF

echo "[build_installer] 🎨 Generating icons..."
python src/desktop_app/desktop_assets/generate_icons.py

echo "[build_installer] 🧹 Cleaning previous builds..."
rm -rf build dist

echo "[build_installer] 📦 Running PyInstaller..."
python -m PyInstaller claire.spec

if [[ -d dist/Claire ]]; then
    echo
    echo "[build_installer] ✅ SUCCESS"
    echo "                  Bundle: ${PROJECT_ROOT}/dist/Claire"
    echo "[build_installer] ℹ️  No installer is produced on Linux."
else
    echo "[build_installer] ❌ Bundle missing at dist/Claire" >&2
    exit 1
fi
